// ── Цена 1: круг через владельца становится частью пути до экрана ─────────

data class SearchState(val query: String, val items: List<String>, val visible: List<String>)

// Плохо: фильтрация 5000 элементов стоит между нажатием клавиши и буквой на
// экране. Дело не в UDF — дело в том, что круг сделал синхронным то, что
// раньше было локальным.
fun reduceSlow(state: SearchState, query: String) = state.copy(
    query = query,
    visible = state.items.filter { it.contains(query) },
)

// Лучше: наверх по-прежнему идёт каждое нажатие (владелец один), но тяжёлое
// вычисление снято с пути ввода и питается от debounce'нутого значения.
fun reduceFast(state: SearchState, query: String) = state.copy(query = query)
// visible пересчитывается отдельным потоком: state.map { it.query }
//   .debounce(300).mapLatest { ... }

